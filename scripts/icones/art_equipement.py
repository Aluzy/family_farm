# Comme scripts/icones/art_outils.py : une majuscule est une matière, ombrée d'elle-même (reflet en
# haut à gauche, ombre en bas à droite, contour sombre de sa teinte posé autour) ; une minuscule
# est une couleur fixe (un détail). Les couleurs sont celles des calques du portrait
# (scripts/personnage/equipement.py) : l'icône et ce qu'on voit sur le membre se ressemblent.
from PIL import Image

# matière : (contour, ombre, moyen, reflet)
MATS = {
    'J': ('#3a2414', '#c7862a', '#f2c040', '#fbe38a'),   # le jaune du casque
    'P': ('#4a3418', '#b88a3a', '#e3c06a', '#f6e2a0'),   # la paille
    'C': ('#2a1608', '#5a3418', '#8a5a34', '#b07a48'),   # le cuir
    'K': ('#3a2410', '#9a6a34', '#c89a58', '#e8c888'),   # le cuir clair
    'V': ('#16301a', '#2f5a28', '#4f8a3d', '#7cb860'),   # le vert du tablier
    'B': ('#121a34', '#22305a', '#34508a', '#5a7cb8'),   # le jean
    'L': ('#2a0a10', '#5a1a24', '#8a2a3a', '#b8485a'),   # la laine rouge du manteau
    'F': ('#2a2416', '#8a7a4a', '#b8a46a', '#d8c890'),   # la fibre tressée
    'W': ('#3a1a2a', '#7a5a8a', '#a07ab0', '#c8a8d8'),   # la laine du grand sac
}
FIXE = {
    'l': '#fffad6', 'h': '#ffde78', 'r': '#c8434a', 'y': '#f2c040', 'f': '#ffffff', 'g': '#ece4d4',
    'k': '#5a3418', 'v': '#2f5a28', 'n': '#d8c890',
}


def G(text):
    rows = [r.ljust(16, '.')[:16] for r in text.strip('\n').split('\n')]
    rows += ['.' * 16] * (16 - len(rows))
    return rows


def hexa(c):
    c = c.lstrip('#')
    return tuple(int(c[i:i + 2], 16) for i in (0, 2, 4)) + (255,)


def dessin(rows):
    mask = {(x, y): ch for y, row in enumerate(rows) for x, ch in enumerate(row) if ch not in '. '}
    im = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    for (x, y), ch in mask.items():
        if ch in MATS:
            def dedans(p):
                c = mask.get(p)
                return c is not None and (c == ch or c not in MATS)
            o, d, m, l = MATS[ch]
            c = l if not dedans((x, y - 1)) or not dedans((x - 1, y)) else d if not dedans((x, y + 1)) or not dedans((x + 1, y)) else m
        else:
            c = FIXE[ch]
        im.putpixel((x, y), hexa(c))
    for y in range(16):
        for x in range(16):
            if (x, y) in mask:
                continue
            for p in ((x, y - 1), (x - 1, y), (x, y + 1), (x + 1, y)):
                c = mask.get(p)
                if c in MATS:
                    im.putpixel((x, y), hexa(MATS[c][0]))
                    break
                if c is not None:
                    im.putpixel((x, y), hexa('#2a1a10'))
    return im


