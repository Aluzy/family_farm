def engrenage():
    cx = cy = 8.0

    def f(x, y):
        dx, dy = x - cx, y - cy
        r = math.hypot(dx, dy)
        a = math.atan2(dy, dx) + math.pi / 8
        dent = math.cos(8 * a) > 0.05
        if r <= 1.7:
            return '.'
        if r <= 5.0 or (dent and r <= 6.6):
            return 'A'
        return '.'
    return compose(geo(f))


