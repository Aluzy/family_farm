# Les icônes sont décrites en « calques » : chaque calque est une grille 16×16 où une majuscule
# désigne une matière (ombrée automatiquement : reflet en haut à gauche, ombre en bas à droite,
# contour 1 px très sombre de la teinte de la matière posé autour) et une minuscule / un chiffre
# une couleur fixe (détails). Les calques sont empilés : le contour d'un calque passe par-dessus
# les calques du dessous, ce qui sépare proprement les objets qui se croisent.
