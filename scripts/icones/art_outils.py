del FIX['Y']


def G(text):
    """Grille 16×16 à partir d'un bloc de texte (rangées complétées par des points)."""
    rows = [r for r in text.strip('\n').split('\n')]
    rows = [r.ljust(16, '.')[:16] for r in rows]
    rows += ['.' * 16] * (16 - len(rows))
    assert len(rows) == 16, rows
    return rows


def geo(f):
    """Grille calculée : f(x, y) renvoie une lettre ou '.' (x, y = centre du pixel)."""
    return [''.join(f(x + .5, y + .5) for x in range(16)) for y in range(16)]


def layer(rows, outline=True):
    mask = {}
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch not in '. ':
                mask[(x, y)] = ch
    out = {}
    for (x, y), ch in mask.items():
        if ch in MATS:
            def ins(p):
                c = mask.get(p)
                return c is not None and (c == ch or c not in MATS)
            o, d, m, l = MATS[ch]
            if not ins((x, y - 1)) or not ins((x - 1, y)):
                out[(x, y)] = l
            elif not ins((x, y + 1)) or not ins((x + 1, y)):
                out[(x, y)] = d
            else:
                out[(x, y)] = m
        else:
            out[(x, y)] = FIX[ch][0]
    if outline:
        for y in range(16):
            for x in range(16):
                if (x, y) in mask:
                    continue
                col = None
                for p in ((x, y - 1), (x - 1, y), (x, y + 1), (x + 1, y)):
                    c = mask.get(p)
                    if c is None:
                        continue
                    oc = MATS[c][0] if c in MATS else FIX[c][1]
                    if oc and (col is None or c in MATS):
                        col = oc
                        if c in MATS:
                            break
                if col:
                    out[(x, y)] = col
    return out


def compose(*layers, put=None):
    px = {}
    for lay in layers:
        if isinstance(lay, list):
            lay = layer(lay)
        px.update(lay)
    if put:
        for (x, y), ch in put.items():
            px[(x, y)] = FIX[ch][0] if ch in FIX else ch
    im = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    for (x, y), c in px.items():
        if 0 <= x < 16 and 0 <= y < 16:
            h = c.lstrip('#')
            im.putpixel((x, y), tuple(int(h[i:i + 2], 16) for i in (0, 2, 4)) + (255,))
    return im


def mirror(rows):
    return [r[::-1] for r in rows]


def seg_dist(px, py, ax, ay, bx, by):
    vx, vy = bx - ax, by - ay
    t = max(0, min(1, ((px - ax) * vx + (py - ay) * vy) / (vx * vx + vy * vy)))
    return math.hypot(px - ax - t * vx, py - ay - t * vy), t


