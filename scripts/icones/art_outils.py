def cle_geo(head, tail, rh=3.3, rw=1.1, ring=True):
    """Clé plate : tête ouverte en `head`, manche jusqu'à `tail`."""
    hx, hy = head
    tx, ty = tail
    ax, ay = hx - tx, hy - ty
    n = math.hypot(ax, ay)
    ax, ay = ax / n, ay / n

    def f(x, y):
        dx, dy = x - hx, y - hy
        u = dx * ax + dy * ay
        v = -dx * ay + dy * ax
        if math.hypot(dx, dy) <= rh / 1.0 * 0.82:
            if u > -0.3 and abs(v) < 0.9:
                return '.'
            return 'A'
        d, t = seg_dist(x, y, tx, ty, hx, hy)
        if d <= rw:
            return 'A'
        return '.'
    return geo(f)


def cle():
    return compose(cle_geo((10.6, 5.4), (3.4, 12.6), rh=5.2, rw=1.45))


def marteau_cle():
    def manche(x, y):
        d, t = seg_dist(x, y, 3.2, 13.2, 10.5, 5.5)
        return 'W' if d <= 1.0 else '.'

    def tete(x, y):
        cx, cy = 11.0, 4.6
        u = ((x - cx) + (y - cy)) / math.sqrt(2)
        v = ((x - cx) - (y - cy)) / math.sqrt(2)
        return 'A' if abs(u) <= 3.4 and abs(v) <= 1.5 else '.'
    cl = cle_geo((4.6, 4.6), (12.8, 12.8), rh=4.2, rw=1.05)
    return compose(geo(manche), geo(tete), cl)


